def manual_docs():
    return [
        {"id": i, "title": t, "description": d, "category": c, "tags": tags, "published_at": dt}
        for (i, t, d, c, tags, dt) in MANUAL_DOCS
    ]


def generate_catalog(seed=SEED, total=TOTAL):
    """Возвращает список документов: 28 ручных + (total - 28) случайных."""
    rnd = random.Random(seed)
    docs = manual_docs()
    span_days = (DATE_END - DATE_START).days
    categories = sorted(CATEGORIES)  # sorted -> порядок не зависит от версии Python
    for n in range(1, total - len(docs) + 1):
        cat = rnd.choice(categories)
        subj, subj2 = rnd.sample(CATEGORIES[cat], 2)
        aspect = rnd.choice(ASPECTS)
        title = f"{subj}: {aspect}"
        description = f"{rnd.choice(INTRO)} «{subj}». Затрагиваются также вопросы: {subj2}. {rnd.choice(OUTRO)}"
        tags = [subj.lower(), subj2.lower(), rnd.choice(LEVEL_TAGS)]
        published = DATE_START + timedelta(days=rnd.randint(0, span_days))
        docs.append({
            "id": f"doc-{n:04d}",
            "title": title,
            "description": description,
            "category": cat,
            "tags": tags,
            "published_at": published.isoformat(),
        })
    return docs


def save_jsonl(docs, path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for d in docs:
            f.write(json.dumps(d, ensure_ascii=False) + "\n")


def load_jsonl(path):
    with Path(path).open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def main():
    p = argparse.ArgumentParser(description="Генерация синтетического каталога")
    p.add_argument("--seed", type=int, default=SEED)
    p.add_argument("--total", type=int, default=TOTAL)
    p.add_argument("--out", default=str(DEFAULT_OUT))
    a = p.parse_args()
    docs = generate_catalog(a.seed, a.total)
    save_jsonl(docs, a.out)
    print(f"Сохранено документов: {len(docs)} (seed={a.seed}) -> {a.out}")


if __name__ == "__main__":
    main()
